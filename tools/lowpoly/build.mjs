// Builds the low-poly miniatures (tools/packages/SPEC.md, "Miniatures"): the shell's own into lowpoly.js at the root
// (tools/lowpoly/shell.js after kit b: the design room's, the studio's and the shell's circles' icons), and each story
// package's into its own file (packages/<key>/src/minis.js after the kit it names, written to the file its story.json
// names in minis, minis.js), with the design room's cards of its miniatures (from its src/props.json and every other
// catalogue) and its station icon marked (story.json's icon). HOST.lowpoly(name) in index.html loads a file when a
// miniature in it is first asked for (a station's icon, the design room's table). Every miniature is built here with
// three.js (the app's three.min.js) and its triangles counted: a wrong tris, or more than 1,200, fails the build.
// usage (from the repository root): node tools/lowpoly/build.mjs          -> writes lowpoly.js and every package's file
//                                   node tools/lowpoly/build.mjs --check  -> exits 1 if any is out of date or wrong
//                                   --only <key>[,<key>]: those packages (and not lowpoly.js); --root <dir>: another copy
// A package found here needs no change to this folder: any packages/<key>/src/minis.js is built. The harnesses
// (harness-a.html, harness-b.html) load the sources themselves, so they need no build.
import fs from 'fs';
import path from 'path';
import { assemble, list, measure, problems, card, catalogue, packageKeys, ROOT } from './minis.mjs';
const ARGS = process.argv.slice(2), opt = n => { const i = ARGS.indexOf(n); return i >= 0 ? ARGS[i + 1] : null; };
const root = opt('--root') ? path.resolve(opt('--root')) : ROOT, check = ARGS.includes('--check');
const only = opt('--only') ? opt('--only').split(',') : null;
const outs = [], bad = [];
const rel = f => path.relative(root, f).split(path.sep).join('/');

// one built file: its entries checked and measured
function take(file, text, prefix) {
  let M;
  try { M = list(text, rel(file)); } catch (e) { bad.push(`${rel(file)}: ${e.message}`); return null; }
  for (const p of problems(M, prefix)) bad.push(`${rel(file)}: ${p}`);
  let got = {};
  try { got = measure(text, rel(file)); } catch (e) { bad.push(`${rel(file)}: ${e.message}`); }
  for (const k of Object.keys(M)) {
    if (typeof got[k] === 'string') bad.push(`${rel(file)}: ${k} does not build: ${got[k]}`);
    else if (got[k] !== undefined && got[k] !== M[k].tris) bad.push(`${rel(file)}: ${k} lists ${M[k].tris} triangles but has ${got[k]}`);
  }
  outs.push({ file, text, n: Object.keys(M).length });
  return M;
}

// ---- the shell's own: lowpoly.js
if (!only) {
  const src = fs.readFileSync(path.join(root, 'tools/lowpoly/shell.js'), 'utf8');
  take(path.join(root, 'lowpoly.js'), assemble(`// The shell's own low-poly miniatures: LOWPOLY_MODELS['<story>.<set>'] = { story, set, name, shows, tris,
// build(THREE) }, each build a THREE.Group centred on x and z, standing on y = 0 and fitting a 1 x 1 x 1 box: the
// station icons of the design room, the studio and the shell's circles. A story's miniatures are in its package
// (packages/<key>/minis.js). Generated by tools/lowpoly/build.mjs from tools/lowpoly/shell.js and kit-b.js: edit those
// and rebuild (node tools/lowpoly/build.mjs), never this file.
`, src), '');
}

// ---- every package with miniatures
const cat = catalogue(root);
for (const key of packageKeys(root)) {
  if (only && !only.includes(key)) continue;
  const base = path.join(root, 'packages', key), sf = path.join(base, 'src/minis.js');
  if (!fs.existsSync(sf)) continue;
  let sj = {};
  try { sj = JSON.parse(fs.readFileSync(path.join(base, 'story.json'), 'utf8').replace(/^﻿/, '')); } catch (e) { bad.push(`packages/${key}/story.json: ${e.message}`); continue; }
  const name = sj.minis;
  if (typeof name !== 'string' || !/^[a-z0-9][a-z0-9_-]*\.js$/.test(name)) { bad.push(`packages/${key}/story.json names no minis file (minis: "minis.js") though src/minis.js is there`); continue; }
  const src = fs.readFileSync(sf, 'utf8'), head = `// The miniatures of the story package ${key}: LOWPOLY_MODELS['${key}.<set>'] = { story, set, name, shows, tris,
// build(THREE), card, icon } (tools/packages/SPEC.md, "Miniatures"); card: what the design room's card shows, icon: true
// for its stations' icon. Generated by tools/lowpoly/build.mjs from packages/${key}/src/minis.js, its kit in
// tools/lowpoly/ and the catalogue (src/props.json): edit those and rebuild (node tools/lowpoly/build.mjs), never this file.
`;
  let M;
  try { M = list(assemble('', src, ''), `packages/${key}/src/minis.js`); } catch (e) { bad.push(`packages/${key}/src/minis.js: ${e.message}`); continue; }
  const cards = Object.keys(M).map(k => `    ${JSON.stringify(k)}: ${JSON.stringify(card(k, M[k], cat))},`).join('\n');
  const icon = typeof sj.icon === 'string' && sj.icon.startsWith(key + '.') ? sj.icon : '';
  if (icon && !M[icon]) bad.push(`packages/${key}/story.json: icon ${icon} is not one of its miniatures (${Object.keys(M).join(', ')})`);
  const tail = `\n  // the design room's cards (from the catalogue: src/props.json) and the station icon (story.json's icon)
  const CARDS = {\n${cards}\n  };
  for (const k in CARDS) LOWPOLY_MODELS[k].card = CARDS[k];\n` + (icon && M[icon] ? `  LOWPOLY_MODELS[${JSON.stringify(icon)}].icon = true;\n` : '');
  take(path.join(base, name), assemble(head, src, tail), key + '.');
}

for (const b of bad) console.log(b);
if (check) {
  const stale = outs.filter(o => !fs.existsSync(o.file) || fs.readFileSync(o.file, 'utf8') !== o.text).map(o => rel(o.file));
  console.log(stale.length ? `out of date: ${stale.join(', ')}: run node tools/lowpoly/build.mjs` : `the miniatures are up to date (${outs.map(o => `${rel(o.file)} ${o.n}`).join(', ')})`);
  process.exit(stale.length || bad.length ? 1 : 0);
}
if (bad.length) { console.log('nothing written'); process.exit(1); }
let wrote = 0;
for (const o of outs) if (!fs.existsSync(o.file) || fs.readFileSync(o.file, 'utf8') !== o.text) { fs.writeFileSync(o.file, o.text); wrote++; }
console.log(`${wrote ? `wrote ${wrote} file${wrote > 1 ? 's' : ''}` : 'all current'}: ${outs.map(o => `${rel(o.file)} (${o.n}, ${(o.text.length / 1024).toFixed(0)} KB)`).join(', ')}`);
