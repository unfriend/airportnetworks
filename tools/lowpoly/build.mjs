// Merges the low-poly miniatures (models-a.js, models-b.js) into the one file the app loads: lowpoly.js at the root
// (HOST.lowpoly() in index.html loads it once, for the design room's table and the shared rooms' station icons).
// usage (from the repository root): node tools/lowpoly/build.mjs          -> writes lowpoly.js
//                                   node tools/lowpoly/build.mjs --check  -> exits 1 if lowpoly.js is out of date
// The two harnesses (harness-a.html, harness-b.html) load the sources themselves, so they need no build.
import fs from 'fs';
import path from 'path';
import vm from 'vm';
const here = path.dirname(new URL(import.meta.url).pathname), root = path.join(here, '../..');
const read = f => fs.readFileSync(path.join(here, f), 'utf8');
const PARTS = ['models-a.js', 'models-b.js'];
let out = `// Low-poly miniatures of every story's sets: LOWPOLY_MODELS['<story>.<set>'] = { story, set, name, shows, tris,
// build(THREE) }, each build a THREE.Group centred on x and z, standing on y = 0 and fitting a 1 x 1 x 1 box.
// Generated by tools/lowpoly/build.mjs from tools/lowpoly/models-a.js and models-b.js: edit those and rebuild
// (node tools/lowpoly/build.mjs), never this file.
`;
for (const f of PARTS) out += `\n// ================================================================ tools/lowpoly/${f}\n` + read(f).trimEnd() + '\n';
// every entry registers with what the table and the icons read (no three.js needed: build() runs only when asked)
const ctx = {};
vm.runInNewContext(out + '\nthis.LOWPOLY_MODELS = LOWPOLY_MODELS;', ctx, { filename: 'lowpoly.js' });
const M = ctx.LOWPOLY_MODELS || {}, keys = Object.keys(M);
const bad = keys.filter(k => { const m = M[k]; return !(m.story && m.set && k === m.story + '.' + m.set && m.name && m.shows && Number.isInteger(m.tris) && m.tris > 0 && m.tris <= 1200 && typeof m.build === 'function'); });
if (!keys.length || bad.length) { console.log('lowpoly: entries missing a field or over 1,200 triangles: ' + (bad.join(', ') || 'none at all')); process.exit(1); }
const target = path.join(root, 'lowpoly.js');
if (process.argv.includes('--check')) {
  const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === out;
  console.log(same ? `lowpoly.js is up to date (${keys.length} miniatures)` : 'lowpoly.js is out of date: run node tools/lowpoly/build.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, out);
console.log(`wrote lowpoly.js (${keys.length} miniatures, ${(out.length / 1024).toFixed(0)} KB)`);
