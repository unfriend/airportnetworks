// Assembles stories/design.js (the design room: the props table) from the tour's kit (tools/engine/kit.js), the table set
// and engine parts in this folder, and the shell's own props' cards, generated here from tools/design/props.json and the
// shell's miniatures (tools/lowpoly/shell.js: none yet, its four are icons, not props). The stories' miniatures and their
// cards are their packages' (packages/<key>/minis.js, built by tools/lowpoly/build.mjs from src/minis.js and
// src/props.json), loaded by the room at run time (HOST.lowpoly('*'), takeCards): a new package needs no rebuild here.
// usage (from the repository root): node tools/design/build.mjs        -> writes stories/design.js
//                                   node tools/design/build.mjs --check -> exits 1 if stories/design.js is out of date
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { expand } from '../engine/parts.mjs';
import { assemble, list, card, catalogue } from '../lowpoly/minis.mjs';
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.join(here, '../..');
const read = f => fs.readFileSync(path.join(here, f), 'utf8');
const SET_FILES = ['table'];
const ENGINE = ['e2_scene', 'e3_story', 'e4_explore', 'e5_xr', 'e6_panels', 'e7_app'];

// ---- the shell's own cards: one per miniature of lowpoly.js's source that is a prop, in its order
const M = list(assemble('', read('../lowpoly/shell.js'), ''), 'tools/lowpoly/shell.js'), cat = catalogue(root);
// icons, not props: the design room's own, the studio's and the shell's circles' (pages and circles that are not stories)
const ICONS = new Set(['design', 'studio', 'all']);
const CARDS = {};
for (const key of Object.keys(M)) if (!ICONS.has(M[key].story)) CARDS[key] = card(key, M[key], cat);
const cards = '// The shell\'s own props\' cards, generated by tools/design/build.mjs from tools/design/props.json and the shell\'s\n' +
  '// miniatures (the stories\' come from their packages: takeCards): by miniature key, { story, set, name, tris, id, shows,\n' +
  '// size, frame, params: [[name, range, meaning, step]], views: [[name, what it frames]], reusedBy, reuses, file, manifest,\n' +
  '// note }\n' +
  'const DESIGN_CARDS = {\n' + Object.entries(CARDS).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n') + (Object.keys(CARDS).length ? '\n' : '') + '};\n';

// ---- the story
let kit = read('../engine/kit.js')
  .replace("if (typeof module !== 'undefined') module.exports = { makeKit };\n", '')
  .replace(/^(\/\/.*\n)+/, '// Shared helpers for the 3D sets (the tour\'s kit): makeKit(THREE) returns K.\n');
const sets = SET_FILES.map(f => read(`sets/${f}.js`).trimEnd() + '\n\n').join('');
let out = expand(read('engine/e1_head.js'), 'e1_head').replace('//@@KIT@@\n', () => kit).replace('//@@CARDS@@\n', () => cards).replace('//@@SETS@@\n', () => sets);
for (const f of ENGINE) out += expand(read(`engine/${f}.js`), f);
const target = path.join(root, 'stories/design.js');
if (process.argv.includes('--check')) {
  const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === out;
  console.log(same ? 'stories/design.js is up to date' : 'stories/design.js is out of date: run node tools/design/build.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, out);
console.log(`wrote stories/design.js (${(out.length / 1024).toFixed(0)} KB, ${Object.keys(CARDS).length} cards)`);
