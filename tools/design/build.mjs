// Assembles stories/design.js (the design room: the props table) from the tour's kit (tools/lbi/kit.js), the table set
// and engine parts in this folder, and the props' cards, generated here from props.json (only the fields a card shows)
// and the miniatures' names (tools/lowpoly/models-a.js and models-b.js; the models themselves load at run time from
// lowpoly.js, HOST.lowpoly()).
// usage (from the repository root): node tools/design/build.mjs        -> writes stories/design.js
//                                   node tools/design/build.mjs --check -> exits 1 if stories/design.js is out of date
import fs from 'fs';
import path from 'path';
import vm from 'vm';
const here = path.dirname(new URL(import.meta.url).pathname), root = path.join(here, '../..');
const read = f => fs.readFileSync(path.join(here, f), 'utf8');
const SET_FILES = ['table'];
const ENGINE = ['e2_scene', 'e3_story', 'e4_explore', 'e5_xr', 'e6_panels', 'e7_app'];

// ---- the cards: one per miniature, in the miniatures' order
const props = JSON.parse(read('props.json'));
const lp = {};
vm.runInNewContext(read('../lowpoly/models-a.js') + '\n' + read('../lowpoly/models-b.js') + '\nthis.M = LOWPOLY_MODELS;', lp, { filename: 'lowpoly' });
const one = s => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
// at most n characters, cut at a word
const cut = (s, n) => { s = one(s); if (s.length <= n) return s; const t = s.slice(0, n - 1); return t.slice(0, Math.max(t.lastIndexOf(' '), Math.round(n * 0.6))).replace(/[,;:(]+$/, '') + '…'; };
// a param's meaning up to its first aside (a semicolon, a bracket or a full stop), when that leaves enough
const first = s => { s = one(s); const m = /^(.{14,}?)(?:; | \(|\. |: )/.exec(s); return m ? m[1] : s; };
// what the card says besides the catalogue (the two keys of one file, a set that is not a scene of its own)
const NOTES = {
  'micro.organs': 'Not a scene of its own: a library of small organ models (ORGAN3D) that the atlas, the network and the tissue topology story draw.',
};
const CARDS = {};
for (const key of Object.keys(lp.M)) {
  if (lp.M[key].story === 'design') continue;   // (the design room's own miniature: its station icon, not a prop)
  const m = lp.M[key], s = props.sets.find(x => x.story === m.story && x.key === m.set), hw = props.handwrittenStories.find(x => x.story === m.story);
  if (s) {
    const twins = props.sets.filter(x => x !== s && x.file === s.file).map(x => x.story + '/' + x.key);
    CARDS[key] = {
      story: m.story, set: m.set, name: m.name, tris: m.tris, id: s.id, shows: cut(s.shows, 460), size: cut(s.size, 100), frame: cut(s.frame, 170),
      params: s.params.map(p => [p.name, cut(p.range, 40), cut(first(p.meaning), 110), p.eased === false ? 1 : 0]),
      views: s.views.map(v => [v.name, cut(first(v.frames), 80)]),
      reusedBy: s.reusedBy.map(one), reuses: s.reuses.map(one), file: s.file, manifest: s.manifest || '',
      note: NOTES[key] || (twins.length ? `One of ${twins.length + 1} sets in one file, with ${twins.join(', ')}.` : ''),
    };
  } else if (hw) {
    CARDS[key] = {
      story: m.story, set: m.set, name: m.name, tris: m.tris, id: m.story, shows: cut(hw.scenes, 460), size: '', frame: '', params: [], views: [],
      reusedBy: props.sets.filter(x => x.reuses.some(r => r.startsWith(hw.file))).map(x => x.id), reuses: [], file: hw.file, manifest: '',
      note: 'A hand-written story: its scene is code in the story itself, not a set, so it has no params or named views to list.',
    };
  } else throw new Error(`no catalogue entry for the miniature ${key}`);
}
const cards = '// The props\' cards, generated by tools/design/build.mjs from tools/design/props.json and the miniatures\' names: by\n' +
  '// miniature key, { story, set, name, tris, id, shows, size, frame, params: [[name, range, meaning, step]], views:\n' +
  '// [[name, what it frames]], reusedBy, reuses, file, manifest, note }\n' +
  'const DESIGN_CARDS = {\n' + Object.entries(CARDS).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n') + '\n};\n';

// ---- the story
let kit = read('../lbi/kit.js')
  .replace("if (typeof module !== 'undefined') module.exports = { makeKit };\n", '')
  .replace(/^(\/\/.*\n)+/, '// Shared helpers for the 3D sets (the tour\'s kit): makeKit(THREE) returns K.\n');
const sets = SET_FILES.map(f => read(`sets/${f}.js`).trimEnd() + '\n\n').join('');
let out = read('engine/e1_head.js').replace('//@@KIT@@\n', () => kit).replace('//@@CARDS@@\n', () => cards).replace('//@@SETS@@\n', () => sets);
for (const f of ENGINE) out += read(`engine/${f}.js`);
const target = path.join(root, 'stories/design.js');
if (process.argv.includes('--check')) {
  const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === out;
  console.log(same ? 'stories/design.js is up to date' : 'stories/design.js is out of date: run node tools/design/build.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, out);
console.log(`wrote stories/design.js (${(out.length / 1024).toFixed(0)} KB, ${Object.keys(CARDS).length} cards)`);
